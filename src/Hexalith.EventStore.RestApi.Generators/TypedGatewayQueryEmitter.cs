using System.Text;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace Hexalith.EventStore.RestApi.Generators;

/// <summary>Emits typed computed-query bindings from owner Contracts without creating REST routes.</summary>
internal static class TypedGatewayQueryEmitter
{
    private const string AttributeName = "Hexalith.EventStore.Contracts.Queries.QueryResultContractAttribute";

    /// <summary>Exports declared request/result pairs over the existing Gateway client.</summary>
    /// <param name="compilation">The consuming compilation and its directly referenced Contracts.</param>
    /// <param name="generatedNamespace">The resolved namespace for generated code.</param>
    /// <param name="reportDiagnostic">Reports invalid typed query declarations.</param>
    /// <param name="cancellationToken">The generation cancellation token.</param>
    /// <returns>The generated binding source, or null when there is no binding to emit.</returns>
    internal static string? Emit(
        Compilation compilation,
        string generatedNamespace,
        Action<Diagnostic> reportDiagnostic,
        CancellationToken cancellationToken)
    {
        if (compilation.GetTypeByMetadataName("Hexalith.EventStore.Client.Gateway.IEventStoreGatewayClient") is null)
        {
            return null;
        }

        var referencedQueries = compilation.SourceModule.ReferencedAssemblySymbols
            .Where(static assembly => assembly.Name.EndsWith(".Contracts", StringComparison.Ordinal))
            .SelectMany(assembly => Collect(assembly.GlobalNamespace, cancellationToken));
        var queries = Collect(compilation.Assembly.GlobalNamespace, cancellationToken)
            .Concat(referencedQueries)
            .OrderBy(static candidate => candidate.Query.ToDisplayString(), StringComparer.Ordinal);

        var source = new StringBuilder("// <auto-generated />\n#nullable enable\n");
        source.Append("namespace ").Append(generatedNamespace).AppendLine(";");
        source.AppendLine("/// <summary>Typed computed-query bindings over the existing EventStore Gateway.</summary>");
        source.AppendLine("public static class TypedGatewayQueries\n{");
        var emittedQueries = new HashSet<string>(StringComparer.Ordinal);
        foreach ((INamedTypeSymbol query, AttributeData contract) in queries)
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (query.IsStatic)
            {
                ReportInvalidQuery(query, contract, "the request type is static", reportDiagnostic, cancellationToken);
                continue;
            }

            var arguments = contract.ConstructorArguments;
            if (arguments.Length != 3
                || arguments[0] is not { Kind: TypedConstantKind.Type, Value: ITypeSymbol result }
                || arguments[1] is not { Kind: TypedConstantKind.Primitive, Value: string domain }
                || arguments[2] is not { Kind: TypedConstantKind.Primitive, Value: string wireType })
            {
                ReportInvalidQuery(query, contract, "a result type, domain and wire query type are required", reportDiagnostic, cancellationToken);
                continue;
            }

            if (GetResultTypeError(result) is { } error)
            {
                ReportInvalidQuery(query, contract, error, reportDiagnostic, cancellationToken);
                continue;
            }

            string queryName = query.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            if (!emittedQueries.Add(queryName))
            {
                continue;
            }

            string resultName = result.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
            source.AppendLine("    /// <summary>Submits the declared query with caller-owned authentication and an opaque target.</summary>");
            source.Append("    public static global::System.Threading.Tasks.Task<global::Hexalith.EventStore.Client.Gateway.EventStoreQueryResult<")
                .Append(resultName).AppendLine(">> QueryAsync(");
            source.AppendLine("        this global::Hexalith.EventStore.Client.Gateway.IEventStoreGatewayClient gateway,");
            source.Append("        string tenantId, string aggregateId, ").Append(queryName).AppendLine(" query,");
            source.AppendLine("        global::System.Threading.CancellationToken cancellationToken = default)");
            source.AppendLine("    {");
            source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(gateway);");
            source.AppendLine("        global::System.ArgumentNullException.ThrowIfNull(query);");
            source.Append("        return gateway.SubmitQueryAsync<").Append(resultName).AppendLine(">(");
            source.Append("            new global::Hexalith.EventStore.Contracts.Queries.SubmitQueryRequest(tenantId, ")
                .Append(SymbolDisplay.FormatLiteral(domain, true)).Append(", aggregateId, ")
                .Append(SymbolDisplay.FormatLiteral(wireType, true)).AppendLine(",");
            source.AppendLine("                Payload: global::System.Text.Json.JsonSerializer.SerializeToElement(query, global::System.Text.Json.JsonSerializerOptions.Web)),");
            source.AppendLine("            null, cancellationToken);\n    }");
        }

        source.AppendLine("}");
        return emittedQueries.Count > 0 ? source.ToString() : null;
    }

    private static void ReportInvalidQuery(
        INamedTypeSymbol query,
        AttributeData contract,
        string reason,
        Action<Diagnostic> reportDiagnostic,
        CancellationToken cancellationToken)
        => reportDiagnostic(Diagnostic.Create(
            RestApiDiagnosticDescriptors.InvalidTypedGatewayQuery,
            contract.ApplicationSyntaxReference?.GetSyntax(cancellationToken).GetLocation() ?? Location.None,
            query.ToDisplayString(),
            reason));

    private static string? GetResultTypeError(ITypeSymbol type, bool isContainingType = false)
    {
        if (type is IArrayTypeSymbol array)
        {
            return GetResultTypeError(array.ElementType);
        }

        if (type is not INamedTypeSymbol named
            || named.TypeKind == TypeKind.Error
            || named.IsUnboundGenericType
            || (!isContainingType && (named.IsStatic || named.IsRefLikeType || named.SpecialType == SpecialType.System_Void)))
        {
            return $"result type '{type.ToDisplayString()}' is unsupported";
        }

        if (named.DeclaredAccessibility != Accessibility.Public || named.IsFileLocal)
        {
            return $"result type '{named.ToDisplayString()}' is not effectively public";
        }

        if (named.ContainingType is { } containingType && GetResultTypeError(containingType, isContainingType: true) is { } containingError)
        {
            return containingError;
        }

        foreach (ITypeSymbol argument in named.TypeArguments)
        {
            if (GetResultTypeError(argument) is { } argumentError)
            {
                return argumentError;
            }
        }

        return null;
    }

    private static IEnumerable<(INamedTypeSymbol Query, AttributeData Contract)> Collect(
        INamespaceSymbol scope,
        CancellationToken cancellationToken)
    {
        cancellationToken.ThrowIfCancellationRequested();
        foreach (INamespaceSymbol child in scope.GetNamespaceMembers())
        {
            foreach (var query in Collect(child, cancellationToken))
            {
                yield return query;
            }
        }

        foreach (INamedTypeSymbol type in scope.GetTypeMembers())
        {
            cancellationToken.ThrowIfCancellationRequested();
            if (type.DeclaredAccessibility == Accessibility.Public
                && type.Arity == 0
                && type.GetAttributes().FirstOrDefault(static attribute => attribute.AttributeClass?.ToDisplayString() == AttributeName) is { } contract)
            {
                yield return (type, contract);
            }
        }
    }
}
